'use strict';
const assert=require('node:assert/strict');
const {assess}=require('../../scripts/paper-v4/build-ranking-forward.cjs');
const make=(ticker='MOCK')=>({ticker,symbolVerified:true,officiallyVerifiedLatestSession:false,primarySource:'test',warnings:[],sessions:Array.from({length:90},(_,i)=>({date:new Date(Date.UTC(2026,0,i+1)).toISOString().slice(0,10),open:10+i*.02,high:10.2+i*.02,low:9.8+i*.02,close:10+i*.02,volume:500000}))});
const h=make(),date=h.sessions.at(-1).date;
const live=assess(h,date);
assert(live.reasons.includes('FILTER_PRICE_VERIFICATION'));
const old=assess(h,'2026-03-10');
assert(old.reasons.includes('STALE_LAST_SESSION'));
const back=assess({...h,lastSession:date},date,'historical');
assert(!back.reasons.includes('FILTER_PRICE_VERIFICATION'));
const blocked=assess(make('SAIB'),date);
assert(blocked.reasons.includes('BLOCKED_BY_POLICY'));
console.log('V4 regression guards pass: stale/blocked/verification history');
