#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(process.env.GITHUB_WORKSPACE||process.cwd());
const read=p=>{try{return JSON.parse(fs.readFileSync(path.join(root,p),'utf8'))}catch{return null}};
const gates=read('04_ACCEPTANCE_GATES.json');
const metrics=read('docs/astra/G11_DATA_HEALTH_METRICS.json');
const truth=read('data/stable/v15-price-truth.json');
const gaps=read('docs/astra/G11_CURRENT_UNIVERSE_GAPS.json');
const problems=read('docs/astra/G11_DATA_HEALTH_ISSUES.json');
const statuses=Object.fromEntries((gates?.gates||[]).map(x=>[x.id,x.status]));
const b=[];
const need=(ok,msg)=>{if(!ok)b.push(msg)};
need(!!metrics,'NO_G11_METRICS');need(!!truth,'NO_ACCEPTED_PRICE_TRUTH');need(!!gates,'NO_GATE_MANIFEST');
const active=metrics?.activeUniverse?.count;
const current=metrics?.currentCanonicalSecurities?.numerator;
const ready=metrics?.decisionPipeline?.pipelineReadySecurities;
const session=metrics?.latestExpectedSession;
need(Number.isInteger(active)&&Number.isInteger(current)&&Number.isInteger(ready),'INVALID_G11_COUNTS');
need(session&&truth?.expectedSession===session,'PRICE_TRUTH_G11_SESSION_MISMATCH');
need(Number.isInteger(active)&&Number.isInteger(current)&&Number.isInteger(ready)&&active>0&&current>=0&&ready>=0&&current<=active&&ready<=current,'IMPOSSIBLE_COVERAGE');
need(!!gaps&&gaps.expectedSession===session&&gaps.activeUniverse===active&&gaps.currentValidCanonicalUniverse===current&&gaps.gapCount===active-current,'UNRECONCILED_GAP_LEDGER');
need(statuses.G09==='GREEN','G09_NOT_CERTIFIED');
need(statuses.G11==='GREEN','G11_NOT_CERTIFIED');
const critical=problems?.criticalUnresolved, high=problems?.highProductionRelevantUnresolved??problems?.highUnresolved;
need(Number.isInteger(critical)&&critical===0&&Number.isInteger(high)&&high===0,'G11_SEVERE_FINDINGS');
need(!!metrics&&metrics.missingSessions?.unresolvedAfterLegitimateExceptions===0,'UNRESOLVED_CURRENT_MISSING_SESSIONS');
need(!!metrics&&metrics.strategyInputReadiness?.productionCritical?.unresolved===0,'UNRESOLVED_STRATEGY_INPUTS');
need(!!metrics&&metrics.stale?.productionCriticalRecords===0,'STALE_PRODUCTION_CRITICAL');
need(statuses.G19==='GREEN'&&gates?.certified===true,'ASTRA_FULL_CERTIFICATION_MISSING');
const report={schemaVersion:'egx-recovery-readiness-2',runAt:new Date().toISOString(),session,priceTruthSession:truth?.expectedSession||null,counts:{active,currentCanonical:current,pipelineReady:ready,canonicalGap:Number.isInteger(active)&&Number.isInteger(current)?active-current:null,modelGap:Number.isInteger(active)&&Number.isInteger(ready)?active-ready:null},gateStates:{G09:statuses.G09||'UNKNOWN',G11:statuses.G11||'UNKNOWN',G19:statuses.G19||'UNKNOWN'},status:b.length?'BLOCKED':'SOURCE_EVIDENCE_PASS',blockers:b,paperTradingExecutable:false,remark:'A passing source-evidence audit does NOT enable execution without separate order/ledger acceptance'};
const out=process.env.EGX_RECOVERY_OUT||'artifacts/history-recovery';
fs.mkdirSync(path.resolve(root,out),{recursive:true});
fs.writeFileSync(path.resolve(root,out,'readiness-evidence.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));if(b.length)process.exitCode=2;
