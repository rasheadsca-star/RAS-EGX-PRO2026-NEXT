#!/usr/bin/env node
'use strict';
const fs=require('fs');
const path=require('path');
const ROOT=path.resolve(process.env.GITHUB_WORKSPACE||process.cwd());
const seed=path.join(ROOT,'scripts/stable/v18-forward-ledger-seed.cjs');
const engine=path.join(ROOT,'scripts/stable/v18-global-strategy-ensemble.cjs');
const extension=path.join(ROOT,'scripts/stable/v18-leadership-extension.cjs');
const ranking=path.join(ROOT,'scripts/stable/v18-evidence-ranking.cjs');
const performance=path.join(ROOT,'scripts/stable/v18-engine-performance-league.cjs');
const unified=path.join(ROOT,'scripts/stable/v18-unified-decision-center.cjs');
const positionPerformance=path.join(ROOT,'scripts/stable/v18-recommendation-position-performance.cjs');
const performanceUi=path.join(ROOT,'preview-v18/performance.js');
const positionUi=path.join(ROOT,'preview-v18/position-performance.js');
const appPath=path.join(ROOT,'preview-v18/app.js');
const source=path.join(ROOT,'data/stable/v18-global-strategy-ensemble.json');
const ledgerSource=path.join(ROOT,'data/stable/v18-forward-ledger.json');
const outDir=path.join(ROOT,'preview-v18');
const out=path.join(outDir,'data.json');
const ledgerOut=path.join(outDir,'forward-ledger.json');
for(const [file,label] of [[seed,'Forward ledger seed'],[engine,'V18 engine'],[extension,'V18.1 leadership extension'],[ranking,'V18.1 evidence ranking'],[performance,'V18.3 engine performance league'],[unified,'V18.2 unified decision center'],[positionPerformance,'V18.3 recommendation position performance'],[performanceUi,'Performance UI'],[positionUi,'Recommendation position UI']]) if(!fs.existsSync(file))throw new Error(`Missing ${label}`);
require(seed);
require(engine);
require(extension);
require(ranking);
require(performance);
require(unified);
require(positionPerformance);
if(!fs.existsSync(source))throw new Error('V18 unified output was not generated');
const data=JSON.parse(fs.readFileSync(source,'utf8'));
if(!data.sessionId)throw new Error('V18 output missing sessionId');
if(data.schemaVersion!=='18.2.0-shadow')throw new Error(`Unexpected schema ${data.schemaVersion}`);
if(!Array.isArray(data.allCandidates)||!Array.isArray(data.universeScreener))throw new Error('V18 decision/universe arrays missing');
if(!data.leadershipSummary||!data.forwardLedgerSummary||!data.dataHealth||!data.enginePerformanceLeague||!data.recommendationPositionPerformance)throw new Error('V18 required summaries/performance modules missing');
if(data.enginePerformanceLeague.trackingStartsOn!=='2026-09-07'||data.recommendationPositionPerformance.trackingStartsOn!=='2026-09-07')throw new Error('Forward performance must start on 2026-09-07');
if(data.rankingPolicy?.code!=='EVIDENCE_FIRST_THEN_SCORE')throw new Error('V18 evidence ranking not applied');
if(data.dataHealth.status!=='PASS')throw new Error('V18 data integrity did not pass');
let app=fs.readFileSync(appPath,'utf8');
const perfCode=fs.readFileSync(performanceUi,'utf8');
if(!app.includes('function renderEnginePerformanceLeague()')) app+='\n\n'+perfCode+'\n';
const positionCode=fs.readFileSync(positionUi,'utf8');
if(!app.includes('function renderRecommendationPositionPerformance()')) app+='\n\n'+positionCode+'\n';
fs.writeFileSync(appPath,app,'utf8');
fs.mkdirSync(outDir,{recursive:true});
fs.writeFileSync(out,`${JSON.stringify(data,null,2)}\n`,'utf8');
JSON.parse(fs.readFileSync(out,'utf8'));
if(fs.existsSync(ledgerSource)){fs.copyFileSync(ledgerSource,ledgerOut);JSON.parse(fs.readFileSync(ledgerOut,'utf8'));}
console.log(JSON.stringify({board:'preview-v18',schemaVersion:data.schemaVersion,sessionId:data.sessionId,candidates:data.allCandidates.length,universe:data.universeScreener.length,actionable:data.counts?.actionableOrConditional||0,ema:data.counts?.emaMacdContinuationEligible||0,leadership:data.counts?.leadershipResearchEligible||0,vcp:data.counts?.vcpEligible||0,ranking:data.rankingPolicy?.code,features:data.featureManifest?.length||0,dataHealth:data.dataHealth?.status,forward:data.forwardLedgerSummary,performanceLeague:{trackingStartsOn:data.enginePerformanceLeague.trackingStartsOn,engines:data.enginePerformanceLeague.engines.length,withSignals:data.enginePerformanceLeague.summary?.enginesWithSignals,resolved:data.enginePerformanceLeague.summary?.totalResolvedReferenceSignals},recommendationPositionPerformance:{trackingStartsOn:data.recommendationPositionPerformance.trackingStartsOn,bestByTargetCount:data.recommendationPositionPerformance.bestByTargetCount,bestByTargetRate:data.recommendationPositionPerformance.bestByTargetRate}},null,2));
